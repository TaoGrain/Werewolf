_ROLE_ALIASES = {
    "WEREWOLF": "WOLF",
    "WOLF": "WOLF",
    "SEER": "SEER",
    "WITCH": "WITCH",
    "HUNTER": "HUNTER",
    "VILLAGER": "VILLAGER",
}


def role_system_prompt(role_card: Mapping[str, Any]) -> str:
    """根据玩家自己的身份牌生成系统提示词，不接触完整身份表。"""

    raw_role = str(role_card.get("role") or "").upper()
    role = _ROLE_ALIASES.get(raw_role)
    if role is None:
        role_prompt = (
            "当前身份尚未识别。只能按照专属玩家视图和当前任务行动，"
            "不得自行假定身份、阵营或特殊能力。"
        )
    else:
        role_prompt = ROLE_PROMPTS[role]
    return f"{COMMON_SYSTEM_PROMPT}\n\n身份专属指引：\n{role_prompt}"
